export function fieldLabel(key: string): string {
  if (FIELD_LABELS[key]) return FIELD_LABELS[key]
  // 常见后缀合并：如 botTokenFile → 查 tokenFile 或 file
  const camel = key.replace(/([A-Z])/g, ' $1').replace(/^./, (c) => c.toUpperCase()).trim()
  return camel
}
